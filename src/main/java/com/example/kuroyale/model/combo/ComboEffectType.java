package com.example.kuroyale.model.combo;

// Enum representing the types of effects that combos can apply.
public enum ComboEffectType {
    DAMAGE_BOOST,        // Percentage boost to damage
    SPEED_BOOST,         // Percentage boost to movement speed
    HEALTH_BOOST,       // Percentage boost to health/HP
    FLAT_HEALTH_BOOST,  // Flat health boost
    RANGE_BOOST,        // Flat range boost in tiles
    ELIXIR_REFUND       // Refund elixir
}